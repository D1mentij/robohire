import type { Scenario, Scene } from "@/types/contracts";
import { planK1Commands, WALK_SPEED_MPS, STOP_BEFORE_EDGE_M, type K1Command } from "./plan";

/*
 * Scenario + Scene → readable Python script for a real Booster K1, using the official Booster Robotics SDK.
 *
 * SDK facts used (checked 2026-11-23, re-checked 2026-11-27: names match booster_gym deploy.py + b1_loco_client.hpp):
 *  - Python package `booster_robotics_sdk_python` (pip, Linux wheels); the GitHub repo itself ships the C++ SDK:
 *    https://github.com/BoosterRobotics/booster_robotics_sdk (README: "pip install booster_robotics_sdk_python --user")
 *  - Init: `ChannelFactory.Instance().Init(0, net_interface)`, `client = B1LocoClient()`, `client.Init()`
 *    https://github.com/BoosterRobotics/booster_gym/blob/main/deploy/deploy.py (Booster's own Python deploy script)
 *    https://github.com/BoosterRobotics/booster_robotics_sdk/blob/main/example/high_level/b1_loco_example_client.cpp
 *  - Modes: `ChangeMode(RobotMode.kPrepare | kWalking | kDamping)`; kDamping = "robot may fall"
 *    https://github.com/BoosterRobotics/booster_robotics_sdk/blob/main/include/booster/robot/common/robot_shared.hpp
 *  - Locomotion: `Move(vx m/s, vy m/s, vyaw rad/s)`; `WaveHand(HandAction.kHandOpen | kHandClose)` (K1 | T1 | T2)
 *    https://github.com/BoosterRobotics/booster_robotics_sdk/blob/main/include/booster/robot/b1/b1_loco_client.hpp
 *    https://github.com/BoosterRobotics/booster_robotics_sdk/blob/main/include/booster/robot/b1/b1_api_const.hpp
 *  - Speech exists only as AiClient.Speak (needs an active AI chat session) or LuiClient TTS (cloud credentials):
 *    https://github.com/BoosterRobotics/booster_robotics_sdk/blob/main/include/booster/robot/ai/client.hpp
 *  NOT verified: Python names of the HandAction enum, the vyaw sign (we assume ROS convention, + = left),
 *  any "point" gesture API (none exists; would need MoveHandEndEffectorV2 + a hand posture), Python TTS signatures.
 *  booster.tech / booster.feishu.cn developer docs could not be fetched.
 *
 * Every call we could NOT confirm in the official sources is wrapped in a Python function whose name starts
 * with UNVERIFIED_ and only prints what it would do, so the script never sends an unknown command to the robot.
 */

export interface ExportMeta {
  businessType?: string | null;
  /** e.g. "shift (3 jobs)" or the job title */
  what?: string;
  generatedAt?: Date;
}

const py = (s: string) => JSON.stringify(s); // JSON string literal is a valid Python str literal for our text
const comment = (s: string) => s.replace(/[\r\n]+/g, " ").slice(0, 120);

function line(c: K1Command): string {
  switch (c.kind) {
    case "turn":
      return `turn(${c.deg.toFixed(1)})  # ${c.deg >= 0 ? "left" : "right"}, face ${comment(c.toward)}`;
    case "walk":
      return `walk(${c.meters.toFixed(2)})  # ~${c.seconds.toFixed(1)} s, stop ${STOP_BEFORE_EDGE_M} m before ${comment(c.toward)}`;
    case "wave":
      return `wave()`;
    case "point":
      return `point(${py(c.toward)})`;
    case "say":
      return `say(${py(c.text)})`;
    case "wait":
      return `time.sleep(${c.seconds})`;
    case "note":
      return `# ${comment(c.text)}`;
  }
}

export function scriptFileName(scenario: Scenario): string {
  const id = scenario.job_id.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "") || "scenario";
  return `robohire_k1_${id}.py`;
}

export function toBoosterScript(scenario: Scenario, scene: Scene, meta: ExportMeta = {}): string {
  const plan = planK1Commands(scenario, scene);
  const startZone = scene.zones.find((z) => z.id === plan.start.zone);
  const when = (meta.generatedAt ?? new Date()).toISOString().slice(0, 16).replace("T", " ");
  const what = meta.what ?? (scenario.job_id === "shift" ? "whole shift" : `job "${scenario.job_id}"`);
  const body: string[] = [];
  let lastLabel: string | undefined;
  let si = 0;
  // re-walk the scenario only to place step comments/labels next to the commands
  const stepLines = plan.commands.map(line);
  for (const s of scenario.steps) {
    if (s.label && s.label !== lastLabel) {
      body.push("", `    # ---- ${comment(s.label)} ----`);
      lastLabel = s.label;
    }
    si++;
    body.push(`    # step ${si}: ${s.action}${s.target ? ` ${s.target}` : ""}`);
    const n = commandsForStep(scenario, scene, si - 1);
    for (let k = 0; k < n; k++) body.push(`    ${stepLines.shift()}`);
  }

  return `#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generated by RoboHire on ${when} UTC.
Business: ${comment(meta.businessType?.trim() || "unknown")}
Scenario: ${comment(what)} (scenario job_id "${comment(scenario.job_id)}", ${scenario.steps.length} steps)

!!! SAFETY: review this script before running it.
!!! Keep a trained safety operator next to the robot and the emergency stop within reach.
!!! Clear the walking path; distances come from a video estimate, not a measured map.

Booster K1 via the official Booster Robotics SDK (Python binding).
Start pose: robot standing in the middle of "${comment(startZone?.label ?? "the room")}", facing the room's +X direction
(along the room width). Walking is open-loop: speed ${WALK_SPEED_MPS} m/s x time, no obstacle detection.
Usage:  python3 ${scriptFileName(scenario)} <network_interface>   (e.g. eth0, or 127.0.0.1 for the simulator)
"""
import math
import sys
import time

try:
    import booster_robotics_sdk_python as sdk
    from booster_robotics_sdk_python import B1LocoClient, ChannelFactory, RobotMode
except ImportError:
    print("Install the Booster SDK first:  pip install booster_robotics_sdk_python --user")
    sys.exit(1)

WALK_SPEED = ${WALK_SPEED_MPS}        # m/s forward
TURN_SPEED = 0.5        # rad/s yaw; sign UNVERIFIED (assumed + = left, ROS convention): test a small turn first
SETTLE = 0.5            # s pause after each motion

client = None


def connect(net_interface):
    """Verified: ChannelFactory + B1LocoClient init, then stand (kPrepare) and enter walking mode (kWalking)."""
    ChannelFactory.Instance().Init(0, net_interface)
    c = B1LocoClient()
    c.Init()
    c.ChangeMode(RobotMode.kPrepare)
    time.sleep(3.0)
    c.ChangeMode(RobotMode.kWalking)
    time.sleep(3.0)
    return c


def wave():
    """WaveHand is verified in the SDK headers (right hand); the Python enum name is looked up defensively."""
    hand_action = getattr(sdk, "B1HandAction", None) or getattr(sdk, "HandAction", None)
    if hand_action is None:
        UNVERIFIED_wave_enum_missing()
        return
    client.WaveHand(hand_action.kHandOpen)
    time.sleep(3.0)
    client.WaveHand(hand_action.kHandClose)
    time.sleep(SETTLE)


def UNVERIFIED_wave_enum_missing():
    print("[UNVERIFIED] HandAction enum not found in this SDK build; skipping wave")


def UNVERIFIED_point_at(zone_label):
    """No pointing API in the SDK. The robot already turned toward the zone; a real arm pose would need
    client.MoveHandEndEffectorV2(posture, time_ms, hand_index) with a measured posture. Prints only."""
    print("[UNVERIFIED] point at: %s" % zone_label)
    time.sleep(1.0)


def UNVERIFIED_speak(text):
    """Speech needs AiClient.Speak(SpeakParameter(text)) inside an AI chat session, or LuiClient TTS with
    cloud credentials (max 1 text/s). Python signatures not verified, so this only prints + waits."""
    print("[K1 says] %s" % text)
    time.sleep(max(2.0, 0.4 * len(text.split())))


def point(zone_label):
    UNVERIFIED_point_at(zone_label)


def say(text):
    UNVERIFIED_speak(text)


def stop():
    client.Move(0.0, 0.0, 0.0)
    time.sleep(SETTLE)


def turn(deg):
    """Turn in place by deg degrees (positive = left / counter-clockwise)."""
    rad = math.radians(deg)
    if abs(rad) < 1e-3:
        return
    client.Move(0.0, 0.0, math.copysign(TURN_SPEED, rad))
    time.sleep(abs(rad) / TURN_SPEED)
    stop()


def walk(meters):
    """Walk straight forward for the given distance at WALK_SPEED."""
    if meters <= 0:
        return
    client.Move(WALK_SPEED, 0.0, 0.0)
    time.sleep(meters / WALK_SPEED)
    stop()


def main():
    global client
    if len(sys.argv) < 2:
        print("usage: python3 %s <network_interface>" % sys.argv[0])
        sys.exit(1)
    client = connect(sys.argv[1])
    try:
${body.length ? body.map((l) => (l ? "    " + l : l)).join("\n") : "        pass"}
    except KeyboardInterrupt:
        print("Interrupted by operator")
    finally:
        stop()
        # stand still; kDamping is NOT used here because the SDK warns the robot may fall in damping mode
        client.ChangeMode(RobotMode.kPrepare)
        print("Done. Robot stopped and standing (kPrepare).")


if __name__ == "__main__":
    main()
`;
}

/** Number of K1 commands produced by scenario step i (plan the prefix i and i+1, diff the lengths). */
function commandsForStep(scenario: Scenario, scene: Scene, i: number): number {
  const a = planK1Commands({ ...scenario, steps: scenario.steps.slice(0, i) }, scene).commands.length;
  const b = planK1Commands({ ...scenario, steps: scenario.steps.slice(0, i + 1) }, scene).commands.length;
  return b - a;
}
