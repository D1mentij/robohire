import assert from "node:assert/strict";
import { mockScene } from "../mocks";
import { planK1Commands, normDeg, STOP_BEFORE_EDGE_M, type K1Command } from "../lib/k1export/plan";
import type { Scenario } from "../types/contracts";
import { toBoosterScript, scriptFileName } from "../lib/k1export/toBoosterScript";
import { buildShiftFallback } from "../lib/ai/shiftFallback";
import { buildPlan } from "../lib/roi/roi";
import { mockJobs } from "../mocks";

const near = (a: number, b: number, eps = 0.051) => assert.ok(Math.abs(a - b) <= eps, `${a} ≉ ${b}`);
const kinds = (c: K1Command[]) => c.map((x) => x.kind);

assert.equal(normDeg(190), -170);
assert.equal(normDeg(-180), 180);
assert.equal(normDeg(360), 0);

// café scene: entrance (5,0.75 2×1.5), counter (8.5,4 2×5), tables (4.5,5.5 5×4), menu_board (8.5,7.25 2×1)
const sc: Scenario = {
  job_id: "t",
  steps: [
    { action: "walk_to", target: "entrance" }, // start pose is the entrance center → already there
    { action: "walk_to", target: "counter" },
    { action: "turn_to", target: "tables" },
    { action: "point_to", target: "menu_board" },
    { action: "walk_to", target: "kitchen" }, // unknown zone → skipped
    { action: "wave" },
    { action: "say", text: "Hello!" },
    { action: "wait", seconds: 2 },
  ],
};
const p = planK1Commands(sc, mockScene);
assert.deepEqual({ x: p.start.x, z: p.start.z, zone: p.start.zone, h: p.start.headingDeg }, { x: 5, z: 0.75, zone: "entrance", h: 0 });
assert.deepEqual(kinds(p.commands), ["note", "turn", "walk", "turn", "turn", "point", "note", "wave", "say", "wait"]);
assert.equal(p.skipped, 1);
const c = p.commands;
// walk_to counter: heading atan2(-3.25, 3.5) = -42.9° (right turn); 4.776 m center-to-center − 1.365 m (center→edge x=7.5) − 0.5 m = 2.91 m
assert.equal(c[1].kind === "turn" && c[1].deg, -42.9);
assert.ok(c[2].kind === "walk");
if (c[2].kind === "walk") {
  near(c[2].meters, 2.91, 0.01);
  near(c[2].seconds, 5.82, 0.02); // 0.5 m/s
}
// stop point (7.134, 2.731) is exactly STOP_BEFORE_EDGE_M from the counter's west edge along the path
{
  const fx = 5 + 3.5 * (2.9118 / Math.hypot(3.5, 3.25));
  near(7.5 - fx, STOP_BEFORE_EDGE_M * (3.5 / Math.hypot(3.5, 3.25)), 0.01);
}
// turn_to tables from (7.134, 2.731): heading atan2(-2.769, -2.634) = -133.6°, delta from -42.9° = -90.7°
assert.equal(c[3].kind === "turn" && c[3].deg, -90.7);
// point_to menu_board (8.5, 7.25): heading atan2(-4.519, 1.366) = -73.2°, delta = +60.4° (left)
assert.ok(c[4].kind === "turn");
if (c[4].kind === "turn") near(c[4].deg, 60.4, 0.15);
assert.deepEqual(c[5], { kind: "point", toward: "Menu board" });
assert.match(c[6].kind === "note" ? c[6].text : "", /unknown zone "kitchen"/);
assert.deepEqual(c[8], { kind: "say", text: "Hello!" });
assert.deepEqual(c[9], { kind: "wait", seconds: 2 });

// turn_to when already facing → no turn command; first target unknown → start at the first scene zone
{
  const q = planK1Commands({ job_id: "q", steps: [{ action: "turn_to", target: "nope" }, { action: "wave" }] }, mockScene);
  assert.equal(q.start.zone, "entrance");
  assert.deepEqual(kinds(q.commands), ["note", "wave"]);
}
// empty scene / empty steps don't crash
assert.deepEqual(planK1Commands({ job_id: "e", steps: [] }, { room: { width: 1, depth: 1 }, zones: [] }).commands, []);

// ---- rendered Python script ----
{
  const py = toBoosterScript(sc, mockScene, { businessType: "Small café", generatedAt: new Date("2026-11-23T10:00:00Z") });
  assert.match(py, /Generated by RoboHire on 2026-11-23 10:00 UTC/);
  assert.match(py, /Business: Small café/);
  assert.match(py, /review this script before running/i);
  assert.match(py, /safety operator/i);
  assert.match(py, /emergency stop/i);
  assert.match(py, /ChannelFactory\.Instance\(\)\.Init\(0, net_interface\)/);
  assert.match(py, /def UNVERIFIED_speak\(/);
  assert.match(py, /def UNVERIFIED_point_at\(/);
  // order of calls inside main(): exactly the planned commands, in order
  const mainBody = py.slice(py.indexOf("    try:\n", py.indexOf("def main(")), py.indexOf("    except KeyboardInterrupt"));
  const calls = mainBody.split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#") && l !== "try:");
  assert.deepEqual(
    calls.map((l) => l.replace(/\(.*$/, "")),
    ["turn", "walk", "turn", "turn", "point", "wave", "say", "time.sleep"],
  );
  assert.ok(calls[0].startsWith("turn(-42.9)"));
  assert.ok(calls[1].startsWith("walk(2.91)"));
  assert.ok(calls[2].startsWith("turn(-90.7)"));
  assert.equal(calls[6], 'say("Hello!")');
  assert.equal(calls[7], "time.sleep(2)");
  assert.match(mainBody, /# skipped walk_to: unknown zone "kitchen"/);
  assert.ok(!/kitchen"\)/.test(mainBody), "no call to an unknown zone");
  assert.equal(scriptFileName(sc), "robohire_k1_t.py");
}
// quotes / newlines in say text stay a single valid string literal
{
  const py = toBoosterScript({ job_id: "q", steps: [{ action: "say", text: 'He said "hi"\nthen\\left' }] }, mockScene);
  assert.ok(py.includes('say("He said \\"hi\\"\\nthen\\\\left")'));
}
// shift export: label section headers + filename
{
  const plan = buildPlan(mockJobs.jobs, 8.5, 60);
  const shift = buildShiftFallback(plan, mockJobs.jobs, mockScene, "Café");
  const py = toBoosterScript(shift, mockScene, { businessType: "Café" });
  assert.match(py, /# ---- Shift start ----/);
  assert.match(py, /# ---- Guide to tables ----/);
  assert.match(py, /Scenario: whole shift/);
  assert.equal(scriptFileName(shift), "robohire_k1_shift.py");
}
