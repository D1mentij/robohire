import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";

/** Stage safety: the full demo path works end to end (demo data only, no video upload). */
test("landing → demo → plan → hire → robot completes → report + .py export", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (e) => errors.push(e.message));

  // 1. landing → Try demo
  await page.goto("/");
  await page.getByTestId("landing-demo-btn").click();
  await expect(page).toHaveURL(/\/jobs/);

  // 2. plan panel shows net €/month
  const panel = page.getByTestId("robot-plan-panel");
  await expect(panel).toBeVisible();
  await expect(panel).toContainText(/net savings/i);
  await expect(panel).toContainText(/€\s?[\d,]+\s*\/\s*mo/);

  // 3. Hire this K1 → /robot (AI may answer or fall back; allow the client timeout)
  await page.getByTestId("hire-plan-btn").click();
  await expect(page).toHaveURL(/\/robot/, { timeout: 45_000 });

  // 4. Start → completion overlay (speech has a time-based fallback, so wait generously)
  const start = page.getByRole("button", { name: /Start/ }).first();
  await expect(start).toBeVisible({ timeout: 30_000 });
  await start.click();
  const done = page.getByTestId("job-completed-card");
  await expect(done).toBeVisible({ timeout: 180_000 });
  await expect(done).toContainText(/completed/i);

  // 5. /report renders, K1 export section + .py download
  await page.goto("/report");
  await expect(page.getByRole("heading", { name: /Robot staffing report/ })).toBeVisible();
  const k1 = page.getByTestId("k1-export");
  await expect(k1).toBeVisible();
  await expect(k1.locator("pre")).toContainText("Generated by RoboHire");
  const [download] = await Promise.all([page.waitForEvent("download"), page.getByTestId("k1-download-py").click()]);
  expect(download.suggestedFilename()).toMatch(/\.py$/);
  const path = await download.path();
  const py = await readFile(path, "utf8");
  expect(py).toContain("Generated by RoboHire");
  expect(py).toMatch(/safety operator/i);
  expect(py).toMatch(/def main\(/);

  expect(errors, `page errors: ${errors.join(" | ")}`).toEqual([]);
});
